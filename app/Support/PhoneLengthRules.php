    public static function dialDigits(?string $countryCode): string
    {
        return ColombiaFormValidation::normalizePhone($countryCode);
    }

    /** @return array{min: int, max: int, pattern?: string} */
    public static function ruleForCountryCode(?string $countryCode): array
    {
        $dial = self::dialDigits($countryCode);
        if ($dial !== '' && isset(self::RULES_BY_DIAL[$dial])) {
            return self::RULES_BY_DIAL[$dial];
        }
        return ['min' => self::DEFAULT_MIN, 'max' => self::DEFAULT_MAX];
    }

    public static function isValidLength(string $digits, ?string $countryCode): bool
    {
        if ($digits === '') {
            return false;
        }
        $rule = self::ruleForCountryCode($countryCode);
        $len = strlen($digits);
        if ($rule['min'] === $rule['max']) {
            if ($len !== $rule['min']) {
                return false;
            }
        } elseif ($len < $rule['min'] || $len > $rule['max']) {
            return false;
        }
        if (! empty($rule['pattern'])) {
            return (bool) preg_match('/'.$rule['pattern'].'/', $digits);
        }
        return true;
    }
